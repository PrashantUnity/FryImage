using System;
using System.Collections.Generic;
using System.Linq;
using Avalonia;
using Avalonia.Media;
using PdfEditorApp.Plugins.ImageEditor.Core.Paint;

namespace PdfEditorApp.Plugins.ImageEditor.Models;

/// <summary>
/// A freehand digital drawing element (Brush, Pencil, Calligraphy, Highlighter, Wet Media).
/// Powered by the FryImage Core Paint Engine with support for:
/// - Professional brush presets and tip profiles
/// - Hardness, Roundness, Angle, Spacing, Flow dynamics
/// - Pencil mode (aliased 1-bit crisp rendering)
/// - Watercolor wet edges (darkened edge perimeter)
/// - Calligraphy chisel tip rendering
/// - Procedural tips (Spatter, Sponge, Star, Foliage, Bristle)
/// - Real-time symmetry passes
/// </summary>
public class DoodleElement : CanvasElement, IHasStroke
{
    public override string ElementType => IsHighlighter ? "Highlighter" : (IsAliased ? "Pencil" : "Drawing");

    public Color StrokeColor { get; set; } = Color.FromArgb(255, 99, 102, 241);
    public double StrokeThickness { get; set; } = 4.0;
    public StrokeDashStyle DashStyle { get; set; } = StrokeDashStyle.Solid;
    public bool IsHighlighter { get; set; }

    // ── Core Brush Engine Properties ──
    public string? BrushPresetId { get; set; }
    public double Hardness { get; set; } = 1.0;
    public double Spacing { get; set; } = 0.25;
    public double Roundness { get; set; } = 1.0;
    public double Angle { get; set; } = 0.0;
    public double Flow { get; set; } = 1.0;
    public bool IsAliased { get; set; }
    public bool HasWetEdges { get; set; }
    public bool HasNoise { get; set; }
    public TipShapeKind TipShape { get; set; } = TipShapeKind.Round;
    public SymmetryMode SymmetryMode { get; set; } = SymmetryMode.Off;

    /// <summary>
    /// Optional pre-computed rich dabs generated by BrushEngine.
    /// </summary>
    public List<BrushDab>? PrecomputedDabs { get; set; }

    /// <summary>
    /// Points in element-local coordinates relative to (X, Y).
    /// </summary>
    public List<Point> Points { get; set; } = new();

    /// <summary>
    /// Reference dimensions at creation time used for aspect scaling on resize.
    /// </summary>
    public double OriginalWidth { get; set; } = 100;
    public double OriginalHeight { get; set; } = 100;

    public DoodleElement()
    {
        Width = 100;
        Height = 100;
        OriginalWidth = 100;
        OriginalHeight = 100;
    }

    /// <summary>
    /// Initializes a DoodleElement from a collection of canvas-space points.
    /// Normalizes points to local space and sets X, Y, Width, Height.
    /// </summary>
    public static DoodleElement FromCanvasPoints(
        IReadOnlyList<Point> canvasPoints,
        Color strokeColor,
        double strokeThickness,
        bool isHighlighter,
        BrushSettings? brushSettings = null,
        string? presetId = null,
        SymmetryMode symmetryMode = SymmetryMode.Off)
    {
        if (canvasPoints == null || canvasPoints.Count == 0)
        {
            return new DoodleElement
            {
                StrokeColor = strokeColor,
                StrokeThickness = strokeThickness,
                IsHighlighter = isHighlighter,
                BrushPresetId = presetId,
                SymmetryMode = symmetryMode
            };
        }

        double minX = canvasPoints.Min(p => p.X);
        double minY = canvasPoints.Min(p => p.Y);
        double maxX = canvasPoints.Max(p => p.X);
        double maxY = canvasPoints.Max(p => p.Y);

        double w = Math.Max(maxX - minX, 8);
        double h = Math.Max(maxY - minY, 8);

        var localPoints = canvasPoints.Select(p => new Point(p.X - minX, p.Y - minY)).ToList();

        // If only 1 point was clicked, add a second micro-offset point so a round dab is drawn
        if (localPoints.Count == 1)
        {
            localPoints.Add(new Point(localPoints[0].X + 0.5, localPoints[0].Y + 0.5));
        }

        var element = new DoodleElement
        {
            X = minX,
            Y = minY,
            Width = w,
            Height = h,
            OriginalWidth = w,
            OriginalHeight = h,
            Points = localPoints,
            StrokeColor = strokeColor,
            StrokeThickness = strokeThickness,
            IsHighlighter = isHighlighter,
            BrushPresetId = presetId,
            SymmetryMode = symmetryMode
        };

        if (brushSettings != null)
        {
            element.Hardness = brushSettings.Hardness;
            element.Spacing = brushSettings.Spacing;
            element.Roundness = brushSettings.Roundness;
            element.Angle = brushSettings.Angle;
            element.Flow = brushSettings.Flow;
            element.IsAliased = brushSettings.Aliased;
            element.HasWetEdges = brushSettings.WetEdges;
            element.HasNoise = brushSettings.Noise;
            element.TipShape = brushSettings.TipShape;

            // Generate precomputed dabs if special tip shape or scattering/dynamics are active
            if (brushSettings.TipShape != TipShapeKind.Round ||
                brushSettings.Scattering.Enabled ||
                brushSettings.ShapeDynamics.Enabled)
            {
                element.PrecomputedDabs = BrushEngine.GenerateDabs(
                    canvasPoints,
                    brushSettings,
                    strokeColor,
                    Colors.White);
            }
        }

        return element;
    }

    public override void Draw(DrawingContext dc)
    {
        if (Points.Count < 2) return;

        double scaleX = OriginalWidth > 0 ? Width / OriginalWidth : 1.0;
        double scaleY = OriginalHeight > 0 ? Height / OriginalHeight : 1.0;

        // Reconstruct canvas-space points
        var transformedPoints = new Point[Points.Count];
        for (int i = 0; i < Points.Count; i++)
        {
            transformedPoints[i] = new Point(
                X + Points[i].X * scaleX,
                Y + Points[i].Y * scaleY);
        }

        // Draw special procedural/scatter dabs if present
        if (PrecomputedDabs != null && PrecomputedDabs.Count > 0)
        {
            DrawDabs(dc, PrecomputedDabs, scaleX, scaleY);
            return;
        }

        var color = StrokeColor;
        if (IsHighlighter && color.A > 140)
        {
            color = Color.FromArgb(120, color.R, color.G, color.B);
        }

        // 1. Watercolour Wet Edges Effect
        if (HasWetEdges)
        {
            DrawWatercolourStroke(dc, transformedPoints, color);
            return;
        }

        // 2. Calligraphy Flat Chisel Tip Effect
        if (TipShape == TipShapeKind.Calligraphy || Roundness < 0.4)
        {
            DrawCalligraphyStroke(dc, transformedPoints, color);
            return;
        }

        // 3. Pencil Mode (Aliased Crisp Stroke)
        if (IsAliased)
        {
            DrawAliasedStroke(dc, transformedPoints, color);
            return;
        }

        // 4. Soft Round Falloff (Hardness < 0.5)
        if (Hardness < 0.5 && StrokeThickness >= 10.0)
        {
            DrawSoftRoundStroke(dc, transformedPoints, color);
            return;
        }

        // 5. Standard Vector Smooth Stroke
        var geometry = BuildSmoothGeometry(transformedPoints);
        var pen = new Pen(
            new SolidColorBrush(color),
            StrokeThickness,
            ShapeDashStyles.ToAvaloniaDashStyle(DashStyle),
            lineCap: PenLineCap.Round,
            lineJoin: PenLineJoin.Round);

        dc.DrawGeometry(null, pen, geometry);
    }

    /// <summary>
    /// Renders pre-computed dabs along the stroke.
    /// </summary>
    private void DrawDabs(DrawingContext dc, IReadOnlyList<BrushDab> dabs, double scaleX, double scaleY)
    {
        foreach (var dab in dabs)
        {
            var center = new Point(
                X + (dab.Center.X - X) * scaleX,
                Y + (dab.Center.Y - Y) * scaleY);

            var dabColor = Color.FromArgb(
                (byte)(dab.Color.A * dab.Opacity),
                dab.Color.R,
                dab.Color.G,
                dab.Color.B);

            var brush = new SolidColorBrush(dabColor);

            if (dab.TipShape == TipShapeKind.Star)
            {
                // Star particle
                var starGeom = BuildStarDabGeometry(center, dab.RadiusX, dab.AngleDegrees);
                dc.DrawGeometry(brush, null, starGeom);
            }
            else if (dab.TipShape == TipShapeKind.Spatter || dab.TipShape == TipShapeKind.Sponge)
            {
                // Cluster droplet
                dc.DrawEllipse(brush, null, center, dab.RadiusX, dab.RadiusY);
            }
            else
            {
                // Elliptical dab with rotation
                using (dc.PushTransform(Matrix.CreateRotation(dab.AngleDegrees * Math.PI / 180.0) * Matrix.CreateTranslation(center.X, center.Y)))
                {
                    dc.DrawEllipse(brush, null, new Point(0, 0), dab.RadiusX, dab.RadiusY);
                }
            }
        }
    }

    /// <summary>
    /// Constructs a 5-pointed star dab geometry.
    /// </summary>
    private static StreamGeometry BuildStarDabGeometry(Point center, double radius, double angleDeg)
    {
        var geom = new StreamGeometry();
        using var ctx = geom.Open();
        double innerR = radius * 0.4;
        double startAngle = angleDeg * Math.PI / 180.0;

        for (int i = 0; i < 10; i++)
        {
            double r = (i % 2 == 0) ? radius : innerR;
            double a = startAngle + i * Math.PI / 5.0;
            var pt = new Point(center.X + r * Math.Cos(a), center.Y + r * Math.Sin(a));
            if (i == 0) ctx.BeginFigure(pt, true);
            else ctx.LineTo(pt);
        }
        ctx.EndFigure(true);
        return geom;
    }

    /// <summary>
    /// Renders authentic Watercolour Wet Edges: a soft translucent body with a darker rim accumulation.
    /// </summary>
    private void DrawWatercolourStroke(DrawingContext dc, IReadOnlyList<Point> pts, Color color)
    {
        var geom = BuildSmoothGeometry(pts);

        // Pass 1: Semi-translucent body wash
        var washColor = Color.FromArgb((byte)(color.A * 0.45 * Flow), color.R, color.G, color.B);
        var washPen = new Pen(new SolidColorBrush(washColor), StrokeThickness, lineCap: PenLineCap.Round, lineJoin: PenLineJoin.Round);
        dc.DrawGeometry(null, washPen, geom);

        // Pass 2: Slightly darker interior core
        var coreColor = Color.FromArgb((byte)(color.A * 0.30 * Flow), color.R, color.G, color.B);
        var corePen = new Pen(new SolidColorBrush(coreColor), StrokeThickness * 0.65, lineCap: PenLineCap.Round, lineJoin: PenLineJoin.Round);
        dc.DrawGeometry(null, corePen, geom);

        // Pass 3: Dark perimeter wet rim
        var rimColor = Color.FromArgb((byte)(color.A * 0.85 * Flow), (byte)Math.Max(0, color.R - 30), (byte)Math.Max(0, color.G - 30), (byte)Math.Max(0, color.B - 30));
        var rimPen = new Pen(new SolidColorBrush(rimColor), Math.Max(1.5, StrokeThickness * 0.18), lineCap: PenLineCap.Round, lineJoin: PenLineJoin.Round);
        dc.DrawGeometry(null, rimPen, geom);
    }

    /// <summary>
    /// Renders Calligraphy Flat Chisel Ribbon Stroke.
    /// </summary>
    private void DrawCalligraphyStroke(DrawingContext dc, IReadOnlyList<Point> pts, Color color)
    {
        double angleRad = Angle * Math.PI / 180.0;
        double halfWidth = StrokeThickness / 2.0;
        double dx = halfWidth * Math.Cos(angleRad);
        double dy = halfWidth * Math.Sin(angleRad);

        var geom = new StreamGeometry();
        using (var ctx = geom.Open())
        {
            // Build upper boundary
            ctx.BeginFigure(new Point(pts[0].X + dx, pts[0].Y + dy), true);
            for (int i = 1; i < pts.Count; i++)
            {
                ctx.LineTo(new Point(pts[i].X + dx, pts[i].Y + dy));
            }
            // Build lower boundary in reverse
            for (int i = pts.Count - 1; i >= 0; i--)
            {
                ctx.LineTo(new Point(pts[i].X - dx, pts[i].Y - dy));
            }
            ctx.EndFigure(true);
        }

        var brush = new SolidColorBrush(color);
        dc.DrawGeometry(brush, null, geom);
    }

    /// <summary>
    /// Renders Aliased (Pencil) Crisp Stroke: integer-locked line segments with square / sharp caps.
    /// </summary>
    private void DrawAliasedStroke(DrawingContext dc, IReadOnlyList<Point> pts, Color color)
    {
        var geom = new StreamGeometry();
        using (var ctx = geom.Open())
        {
            ctx.BeginFigure(pts[0], false);
            for (int i = 1; i < pts.Count; i++)
            {
                ctx.LineTo(pts[i]);
            }
            ctx.EndFigure(false);
        }

        var pen = new Pen(
            new SolidColorBrush(color),
            Math.Max(1.0, Math.Round(StrokeThickness)),
            lineCap: PenLineCap.Square,
            lineJoin: PenLineJoin.Miter);

        dc.DrawGeometry(null, pen, geom);
    }

    /// <summary>
    /// Renders Soft Round Gaussian Falloff stroke via multi-layered alpha falloff.
    /// </summary>
    private void DrawSoftRoundStroke(DrawingContext dc, IReadOnlyList<Point> pts, Color color)
    {
        var geom = BuildSmoothGeometry(pts);

        // 3 concentric layers mimicking Gaussian falloff
        double[] sizeMultipliers = { 1.0, 0.70, 0.40 };
        double[] alphaMultipliers = { 0.25, 0.45, 0.70 };

        for (int i = 0; i < sizeMultipliers.Length; i++)
        {
            var layerColor = Color.FromArgb((byte)(color.A * alphaMultipliers[i] * Flow), color.R, color.G, color.B);
            var layerPen = new Pen(new SolidColorBrush(layerColor), StrokeThickness * sizeMultipliers[i], lineCap: PenLineCap.Round, lineJoin: PenLineJoin.Round);
            dc.DrawGeometry(null, layerPen, geom);
        }
    }

    /// <summary>
    /// Builds a smooth quadratic bezier spline geometry passing through/between points.
    /// </summary>
    public static StreamGeometry BuildSmoothGeometry(IReadOnlyList<Point> pts)
    {
        var geometry = new StreamGeometry();
        using var ctx = geometry.Open();

        if (pts.Count == 0) return geometry;
        if (pts.Count == 1)
        {
            ctx.BeginFigure(pts[0], false);
            ctx.LineTo(new Point(pts[0].X + 0.1, pts[0].Y + 0.1));
            ctx.EndFigure(false);
            return geometry;
        }

        ctx.BeginFigure(pts[0], false);

        if (pts.Count == 2)
        {
            ctx.LineTo(pts[1]);
        }
        else
        {
            // Catmull-Rom / midpoint quadratic smoothing
            for (int i = 0; i < pts.Count - 1; i++)
            {
                var p0 = pts[i];
                var p1 = pts[i + 1];
                var mid = new Point((p0.X + p1.X) / 2.0, (p0.Y + p1.Y) / 2.0);

                if (i == 0)
                {
                    ctx.LineTo(mid);
                }
                else
                {
                    ctx.QuadraticBezierTo(p0, mid);
                }
            }
            ctx.LineTo(pts[^1]);
        }

        ctx.EndFigure(false);
        return geometry;
    }

    public override bool HitTest(Point pt)
    {
        if (!Bounds.Inflate(StrokeThickness / 2 + 8).Contains(pt))
            return false;

        double scaleX = OriginalWidth > 0 ? Width / OriginalWidth : 1.0;
        double scaleY = OriginalHeight > 0 ? Height / OriginalHeight : 1.0;
        double threshold = Math.Max(StrokeThickness / 2.0 + 6.0, 8.0);
        double thresholdSq = threshold * threshold;

        for (int i = 0; i < Points.Count - 1; i++)
        {
            var p1 = new Point(X + Points[i].X * scaleX, Y + Points[i].Y * scaleY);
            var p2 = new Point(X + Points[i + 1].X * scaleX, Y + Points[i + 1].Y * scaleY);

            if (DistanceSquaredToSegment(pt, p1, p2) <= thresholdSq)
                return true;
        }

        return false;
    }

    private static double DistanceSquaredToSegment(Point p, Point a, Point b)
    {
        double dx = b.X - a.X;
        double dy = b.Y - a.Y;
        double lenSq = dx * dx + dy * dy;

        if (lenSq == 0) return PointDistanceSquared(p, a);

        double t = Math.Clamp(((p.X - a.X) * dx + (p.Y - a.Y) * dy) / lenSq, 0, 1);
        var proj = new Point(a.X + t * dx, a.Y + t * dy);
        return PointDistanceSquared(p, proj);
    }

    private static double PointDistanceSquared(Point p1, Point p2)
    {
        double dx = p1.X - p2.X;
        double dy = p1.Y - p2.Y;
        return dx * dx + dy * dy;
    }

    public override CanvasElement Clone()
    {
        var copy = new DoodleElement
        {
            OriginalWidth = OriginalWidth,
            OriginalHeight = OriginalHeight,
            StrokeColor = StrokeColor,
            StrokeThickness = StrokeThickness,
            DashStyle = DashStyle,
            IsHighlighter = IsHighlighter,
            BrushPresetId = BrushPresetId,
            Hardness = Hardness,
            Spacing = Spacing,
            Roundness = Roundness,
            Angle = Angle,
            Flow = Flow,
            IsAliased = IsAliased,
            HasWetEdges = HasWetEdges,
            HasNoise = HasNoise,
            TipShape = TipShape,
            SymmetryMode = SymmetryMode,
            PrecomputedDabs = PrecomputedDabs != null ? new List<BrushDab>(PrecomputedDabs) : null,
            Points = new List<Point>(Points)
        };
        CopyBasePropertiesTo(copy);
        copy.IsLocked = false;
        copy.GroupId = null;
        return copy;
    }
}
